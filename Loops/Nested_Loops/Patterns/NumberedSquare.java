class NumberedSquare {
    public static void main(String[] args) {
        int n = 4;
        
        System.out.println();
        for (int i = 1; i <= n; i++) {
            for (int j = 0; j < n; j++) {
                System.out.print(i + " ");
            }

            System.out.println();
        }

        System.out.println();
    }
}
